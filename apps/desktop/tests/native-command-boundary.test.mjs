import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

test('native handlers have generated permissions and the main window grants only registered commands',()=>{
 const read=file=>readFileSync(new URL(file,import.meta.url),'utf8');
 const host=read('../src-tauri/src/lib.rs');
 const build=read('../src-tauri/build.rs');
 const capability=JSON.parse(read('../src-tauri/capabilities/main-window.json'));
 const handlerList=host.match(/generate_handler!\[([\s\S]*?)\]/)?.[1];
 const manifestList=build.match(/\.commands\(&\[([\s\S]*?)\]/)?.[1];
 assert.ok(handlerList,'Tauri handler registry must be inspectable');
 assert.ok(manifestList,'Tauri app command manifest must be inspectable');
 const handlers=handlerList.split(',').map(value=>value.trim()).filter(Boolean).sort();
 const generated=[...manifestList.matchAll(/"([a-z_]+)"/g)].map(match=>match[1]).sort();
 assert.deepEqual(generated,handlers,'native handlers must be declared for permission generation');
 for(const command of handlers){
  const permission=read(`../src-tauri/permissions/autogenerated/${command}.toml`);
  assert.ok(permission.includes(`commands.allow = ["${command}"]`),`${command}: generated allow permission is missing`);
  assert.ok(permission.includes(`commands.deny = ["${command}"]`),`${command}: generated deny permission is missing`);
 }
 const granted=capability.permissions.filter(value=>value.startsWith('allow-')).map(value=>value.slice(6).replaceAll('-','_')).sort();
 assert.deepEqual(granted,handlers,'the main window must grant exactly the restricted native handlers');
 assert.deepEqual(capability.windows,['main']);
 assert.deepEqual(capability.permissions.filter(value=>!value.startsWith('allow-')).sort(),['core:event:allow-listen','core:event:allow-unlisten','dialog:allow-message']);
 assert.ok(!capability.permissions.includes('dialog:default'),'confirmation does not grant the full dialog bundle');
 assert.ok(!capability.permissions.includes('dialog:allow-open'),'confirmation does not grant unrestricted file picking');
 assert.ok(!capability.permissions.includes('dialog:allow-save'),'confirmation does not grant unrestricted saving');
});
